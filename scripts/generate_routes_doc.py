"""Write docs/ROUTES.md: every route the API serves, including admin routes.

Reads the live FastAPI route table (so it cannot drift from the code). This file is for
developers and is not served by the API (only public/ is mounted).

    python scripts/generate_routes_doc.py            # writes docs/ROUTES.md
    python scripts/generate_routes_doc.py --check    # exit 1 if docs/ROUTES.md is stale

Run it inside the container if importing main.py fails locally:
    docker exec show-me-fire-api python scripts/generate_routes_doc.py
"""
import argparse
import inspect
import logging
import logging.handlers
import os
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "ROUTES.md"
AUTH_HINT = re.compile(r"(admin|auth|require|current_member|verify|token|key|device|ingest_source|station_data)", re.I)


class _NullHandler(logging.NullHandler):
    def __init__(self, *args, **kwargs):  # accept FileHandler's arguments
        super().__init__()


def load_app():
    # Importing main configures file logging; a doc run must not write (or need write access to) logs.
    logging.FileHandler = _NullHandler
    logging.handlers.RotatingFileHandler = _NullHandler
    logging.handlers.TimedRotatingFileHandler = _NullHandler
    sys.path.insert(0, str(ROOT))
    os.chdir(ROOT)
    import main  # noqa: WPS433

    return main.app


def _walk(dependant):
    for sub in dependant.dependencies:
        yield sub
        yield from _walk(sub)


def describe_dependencies(route):
    """(auth/gate names, rate limit text) from a route's dependency tree."""
    from core.rate_limit import RateLimiter

    gates, limit = [], ""
    for sub in _walk(route.dependant):
        call = sub.call
        if isinstance(call, RateLimiter):
            limit = f"{call.per_minute}/min ({call.scope})"
        else:
            name = getattr(call, "__name__", "")
            if name and AUTH_HINT.search(name) and name not in gates:
                gates.append(name)
    return gates, limit


INLINE_ADMIN = re.compile(r"\b_?require_admin\w*\(|\bverify_token\(|\badmin_required\(")


def _inline_admin_check(endpoint):
    try:
        return bool(INLINE_ADMIN.search(inspect.getsource(endpoint)))
    except (OSError, TypeError):
        return False


def auth_level(gates, path, endpoint):
    if any("require_admin" == g for g in gates):
        return "admin"
    if _inline_admin_check(endpoint):
        return "admin (checked in handler)"
    if path.startswith("/api/admin") or path.startswith("/admin/"):
        return "ADMIN PATH, NO CHECK FOUND - verify"
    return ", ".join(gates) if gates else "public"


def collect(app):
    from fastapi.routing import APIRoute, APIWebSocketRoute
    from starlette.routing import Mount

    routes, mounts, sockets = [], [], []
    alias_paths = {r.path for r in app.routes if isinstance(r, APIRoute) and r.name.endswith("_alias")}
    for route in app.routes:
        if isinstance(route, Mount):
            mounts.append(route.path or "/")
        elif isinstance(route, APIWebSocketRoute):
            sockets.append(route.path)
        elif isinstance(route, APIRoute):
            gates, limit = describe_dependencies(route)
            alias = route.name.endswith("_alias")
            twin = route.path[len("/api"):] if route.path.startswith("/api/") else None
            routes.append({
                "methods": ",".join(sorted(m for m in route.methods if m not in ("HEAD", "OPTIONS"))),
                "path": route.path, "module": route.endpoint.__module__, "handler": route.endpoint.__name__,
                "auth": auth_level(gates, route.path, route.endpoint), "limit": limit, "alias": alias,
                "has_alias": bool(twin and twin in alias_paths),
            })
    return routes, mounts, sockets


def render(routes, mounts, sockets):
    groups = defaultdict(list)
    for r in routes:
        groups[r["module"].replace("routers.", "")].append(r)
    total = len(routes)
    admin = sum(1 for r in routes if r["auth"].startswith("admin"))
    unchecked = [r for r in routes if r["auth"].startswith("ADMIN PATH")]
    lines = [
        "# API routes", "",
        "Generated by `scripts/generate_routes_doc.py` from the live route table. Do not edit by hand; "
        "re-run the script (`--check` verifies it is current). Not served by the API.", "",
        f"{total} HTTP routes ({admin} admin). Routes marked *alias* are the unprefixed twins of `/api/...` routes "
        "(`core/api_aliases.py`); they run the same handler with the same auth and limits and are hidden from the OpenAPI schema. "
        "`/api/admin/*` and `/api/graphics/auth/*` are never aliased. New routes should not use the `/api/` prefix.", "",
        "Auth column: `public` = no credentials; `admin` = `require_admin` dependency (admin session cookie); `admin (checked in handler)` = the "
        "handler calls `require_admin`/`verify_token` itself; `ADMIN PATH, NO CHECK FOUND` = under an admin path but no check was "
        "detected (login/logout/OAuth callbacks are expected here, anything else deserves a look); other values name the "
        "dependency that gates the route. Limit column: per-client-IP rate limit (`core/rate_limit.py`).", "",
    ]
    for module in sorted(groups):
        lines += [f"## {module}", "", "| Method | Path | Auth | Limit | Handler | Notes |", "| --- | --- | --- | --- | --- | --- |"]
        for r in sorted(groups[module], key=lambda x: (x["path"], x["methods"])):
            notes = "alias" if r["alias"] else ("has unprefixed alias" if r["has_alias"] else "")
            lines.append(f"| {r['methods']} | `{r['path']}` | {r['auth']} | {r['limit']} | `{r['handler']}` | {notes} |")
        lines.append("")
    lines += ["## Static mounts", ""] + [f"- `{m}`" for m in sorted(mounts)] + [""]
    if sockets:
        lines += ["## WebSockets", ""] + [f"- `{s}`" for s in sorted(sockets)] + [""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    args = parser.parse_args()
    text = render(*collect(load_app()))
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date; run scripts/generate_routes_doc.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
